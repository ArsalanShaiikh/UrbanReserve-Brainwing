// Vectorises the brochure's botanical line art so the site uses the exact same drawings.
// 1. mutool draw -o "p%d.png" -r 400 <brochure.pdf> 2 9 11 27   (into a folder)
// 2. node scripts/trace-botanicals.mjs <that folder> [--preview <dir>]
import sharp from 'sharp'
import potrace from 'potrace'
import fs from 'node:fs'
import path from 'node:path'

const SRC = process.argv[2]
const PREVIEW = process.argv.includes('--preview') ? process.argv[process.argv.indexOf('--preview') + 1] : null
const K = 400 / 90
const TRACE_SCALE = 0.62

// [name, page, x, y, w, h, mode, threshold, opts] in 90dpi preview coordinates.
// mode: 'light' = lines lighter than the ground, 'dark' = darker, 'emboss' = blind emboss relief.
// opts.channel: the cover's olive-on-teal lines only separate cleanly in the red channel.
// opts.soften: pre-blur that reconnects the cover's ~1px source lines once upscaled.
// opts.erase: [x, y, w, h] fractions of the crop to blank out (neighbouring motifs).
const MOTIFS = [
  ['monstera', 2, 382, 418, 118, 145, 'light', 8, { channel: 'red', soften: 1.1, erase: [0.88, 0, 0.12, 0.1] }],
  ['fern', 9, 239, 494, 326, 236, 'dark', 12],
  ['leaf', 2, 540, 508, 132, 158, 'light', 8, { channel: 'red', soften: 1.1, erase: [0.82, 0, 0.18, 0.2] }],
  ['umbel', 11, 1012, 158, 206, 345, 'light', 26, { erase: [0, 0.82, 0.78, 0.18] }],
  ['star', 11, 762, 484, 376, 268, 'light', 26],
  ['seed', 27, 1036, 66, 138, 186, 'emboss', 9],
]

// Separates line work from shading by comparing each pixel to its blurred surroundings.
async function lineMask(buf, mode, t, { channel, soften, erase } = {}) {
  const { data: rgb, info: src } = await sharp(buf).removeAlpha().raw().toBuffer({ resolveWithObject: true })
  const single = Buffer.alloc(src.width * src.height)
  for (let i = 0; i < single.length; i++) {
    const [r, gr, b] = [rgb[i * 3], rgb[i * 3 + 1], rgb[i * 3 + 2]]
    single[i] = channel === 'red' ? r : Math.round(0.299 * r + 0.587 * gr + 0.114 * b)
  }
  let g = sharp(single, { raw: { width: src.width, height: src.height, channels: 1 } })
  if (soften) g = g.blur(soften)
  // sharp re-expands single-channel raw input to sRGB unless told otherwise
  const { data, info } = await g.toColourspace('b-w').raw().toBuffer({ resolveWithObject: true })
  const bg = await sharp(data, { raw: { width: info.width, height: info.height, channels: 1 } }).blur(14).toColourspace('b-w').raw().toBuffer()
  const out = Buffer.alloc(data.length)
  for (let i = 0; i < data.length; i++) {
    const d = data[i] - bg[i]
    const on = mode === 'light' ? d > t : mode === 'dark' ? -d > t : Math.abs(d) > t
    out[i] = on ? 0 : 255
  }
  if (erase) {
    const [ex, ey, ew, eh] = erase
    for (let y = Math.floor(ey * info.height); y < (ey + eh) * info.height; y++)
      for (let x = Math.floor(ex * info.width); x < (ex + ew) * info.width; x++) out[y * info.width + x] = 255
  }
  // the source art is ~1.3px/pt, so tracing at half of 400dpi keeps every real detail with far fewer nodes
  return sharp(out, { raw: { width: info.width, height: info.height, channels: 1 } })
    .median(3)
    .resize({ width: Math.round(info.width * TRACE_SCALE), kernel: 'lanczos3' })
    .threshold(215)
    .toColourspace('b-w')
    .png()
    .toBuffer()
}

const trace = (buf) =>
  new Promise((res, rej) =>
    potrace.trace(buf, { threshold: 128, turdSize: 12, optTolerance: 0.6, alphaMax: 1, blackOnWhite: true }, (e, svg) => (e ? rej(e) : res(svg))),
  )

const out = {}
for (const [name, page, x, y, w, h, mode, t, opts] of MOTIFS) {
  const crop = await sharp(path.join(SRC, `p${page}.png`))
    .extract({ left: Math.round(x * K), top: Math.round(y * K), width: Math.round(w * K), height: Math.round(h * K) })
    .png().toBuffer()
  const mask = await lineMask(crop, mode, t, opts)
  const svg = await trace(mask)
  if (!/ d="/.test(svg)) throw new Error(`${name}: nothing traced, lower its threshold`)
  const d = svg.match(/ d="([^"]+)"/)[1].replace(/\s+/g, ' ').replace(/-?\d+\.\d+/g, (n) => String(Math.round(+n)))
  const [, W, H] = svg.match(/width="(\d+)" height="(\d+)"/)
  out[name] = { w: +W, h: +H, d }
  if (PREVIEW) {
    fs.mkdirSync(PREVIEW, { recursive: true })
    await sharp(mask).toFile(path.join(PREVIEW, `${name}-mask.png`))
    await sharp(Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}"><rect width="100%" height="100%" fill="#1c4436"/><path d="${d}" fill="#e6c983" fill-rule="evenodd"/></svg>`))
      .png().toFile(path.join(PREVIEW, `${name}-vector.png`))
  }
  console.log(name, W, H, d.length)
}

fs.writeFileSync(
  'src/art/botanicalPaths.js',
  '// Generated by scripts/trace-botanicals.mjs from the brochure artwork. Do not edit by hand.\n' +
    `export default ${JSON.stringify(out, null, 0)}\n`,
)
